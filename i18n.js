const I18N_NAMES = {en: 'English', ru: 'Русский'};
// plural forms: en [one, other]; ru [one, few, many]
const I18N_PLURALS = {
  "en": {
    "rule": [
      "rule",
      "rules"
    ]
  },
  "ru": {
    "rule": [
      "правило",
      "правила",
      "правил"
    ]
  }
};
const LANG = (() => {
  const q = new URLSearchParams(location.search).get('lang');
  if (q) localStorage.setItem('lang', q);
  const l = localStorage.getItem('lang') || navigator.language || 'en';
  return (I18N[l.toLowerCase().slice(0, 2)] ? l.toLowerCase().slice(0, 2) : 'en');
})();
function i18n(key, ...args) {
  let s = (I18N[LANG] || {})[key];
  if (s === undefined) s = key;
  return args.length ? s.replace(/\{(\d+)\}/g, (_, i) => args[i] ?? '') : s;
}
function i18nPlural(key, n) {
  const f = (I18N_PLURALS[LANG] || I18N_PLURALS.en)[key] || I18N_PLURALS.en[key] || [key, key];
  n = Math.abs(Math.trunc(n || 0));
  if (LANG === 'ru') { const a = n % 100, b = a % 10; return f[(a > 10 && a < 20) ? 2 : (b > 1 && b < 5) ? 1 : (b === 1) ? 0 : 2]; }
  return f[n === 1 ? 0 : 1];
}
// backend labels: exact match first, then the first word ("Brightness L1" -> "Яркость L1")
function i18nLabel(s) {
  if (!s || typeof s !== 'string') return s;
  const table = I18N[LANG] || {};
  if (table[s] !== undefined) return table[s];
  const sp = s.indexOf(' ');
  if (sp > 0 && table[s.slice(0, sp)] !== undefined) return table[s.slice(0, sp)] + s.slice(sp);
  return s;
}
function localizeDevices(list) {
  for (const d of list || []) for (const c of d.controls || []) c.label = i18nLabel(c.label);
  return list;
}
// static markup (everything outside <script>): text nodes and a few attributes
function translateDom(root) {
  if (root === document) document.documentElement.lang = LANG;
  const table = I18N[LANG] || {};
  const skip = new Set(['SCRIPT', 'STYLE']);
  const walker = document.createTreeWalker(root.body || root, NodeFilter.SHOW_TEXT | NodeFilter.SHOW_ELEMENT);
  for (let n = walker.currentNode; n; n = walker.nextNode()) {
    if (n.nodeType === Node.ELEMENT_NODE) {
      if (skip.has(n.tagName)) { walker.nextSibling(); continue; }
      for (const a of ['title', 'placeholder', 'aria-label', 'alt']) {
        const v = n.getAttribute && n.getAttribute(a);
        if (v && table[v] !== undefined) n.setAttribute(a, table[v]);
      }
    } else if (n.nodeType === Node.TEXT_NODE) {
      const raw = n.nodeValue, key = raw.trim();
      if (key && table[key] !== undefined) n.nodeValue = raw.replace(key, table[key]);
    }
  }
  if (document.title && table[document.title] !== undefined) document.title = table[document.title];
  const b = document.getElementById('langbtn'); if (b) b.textContent = LANG === 'ru' ? 'EN' : 'RU';
}
